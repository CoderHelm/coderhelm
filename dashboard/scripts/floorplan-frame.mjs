#!/usr/bin/env node
// Writes public/app-map/viewer.js from the vendored Floorplan viewer
// (vendor/floorplan, MIT): the viewer's page, its add-ons, the layout engine,
// its fonts and images, as strings the App map frame (public/app-map/frame.js)
// assembles into a map page the way Floorplan's build.mjs does. Nothing here
// enters the dashboard's own JavaScript: the frame loads it as a static file,
// in a sandboxed iframe, only on the App map page.
//
// Runs on install (postinstall) and before dev and build; the output is not
// committed. Vendored files are read as they are, never edited.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ASSETS = path.join(ROOT, 'vendor', 'floorplan', 'skills', 'floorplan', 'assets');
const OUT = path.join(ROOT, 'public', 'app-map', 'viewer.js');

const read = (p) => fs.readFileSync(path.join(ASSETS, p), 'utf8');
const dataUri = (p, type) => `data:${type};base64,${fs.readFileSync(path.join(ASSETS, p)).toString('base64')}`;

// The same font faces build.mjs inlines.
const RANGES = {
  latin: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
  'latin-ext': 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF',
};
const fonts = [['Inter', 'inter'], ['JetBrains Mono', 'jetbrains-mono']]
  .flatMap(([family, file]) => Object.entries(RANGES).map(([subset, range]) =>
    `@font-face{font-family:"${family}";font-style:normal;font-display:swap;font-weight:100 900;unicode-range:${range};src:url(${dataUri(`vendor/fonts/${file}-${subset}-wght-normal.woff2`, 'font/woff2')}) format("woff2")}`))
  .join('\n');

const ui = fs.readdirSync(path.join(ASSETS, 'ui')).filter((n) => n.endsWith('.js')).sort().map((n) => ({ name: n, code: read(`ui/${n}`) }));
const version = fs.readFileSync(path.join(ROOT, 'vendor', 'floorplan', 'VERSION'), 'utf8').trim();

const parts = {
  version,
  template: read('viewer.html'),
  elk: read('vendor/elk.bundled.js'),
  graphQuery: read('graph-query.js'),
  ui,
  fonts,
  logo: dataUri('logo.png', 'image/png'),
  favicon: dataUri('favicon.png', 'image/png'),
};
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, `// Generated by scripts/floorplan-frame.mjs from vendor/floorplan (Floorplan ${version}, MIT). Do not edit.\nwindow.FLOORPLAN_PARTS = ${JSON.stringify(parts)};\n`);
console.log(`wrote public/app-map/viewer.js (Floorplan ${version})`);
