#!/usr/bin/env node
// Writes src/lib/openapi-fields.ts: the fields each schema in the public API's
// OpenAPI document has. The document is generated from the gateway's code in
// coderhelm-platform and committed there at docs/api/openapi.json.
// src/lib/api-contract.ts checks, at type-check time, that every field the
// dashboard's run and plan types read is one the gateway documents, so a field
// the gateway drops fails `npm run typecheck` instead of showing up blank.
//
//   node scripts/openapi-fields.mjs                 regenerate at the commit the file names
//   node scripts/openapi-fields.mjs --ref main      regenerate at the platform's main (or any ref)
//   node scripts/openapi-fields.mjs --check         fail when the file differs from that commit's document
//
// OPENAPI_FILE=path reads a local document instead (with --ref naming its commit).

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = 'CoderHelm/coderhelm-platform';
const SPEC_PATH = 'docs/api/openapi.json';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src/lib/openapi-fields.ts');

const args = process.argv.slice(2);
const check = args.includes('--check');
const refArg = args.includes('--ref') ? args[args.indexOf('--ref') + 1] : undefined;

/** The platform commit the committed file was generated from. */
function recordedRef() {
  const m = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8').match(/OPENAPI_REF = "([0-9a-f]{40})"/);
  return m ? m[1] : undefined;
}

/** A full commit SHA for a branch, tag or SHA in the platform repo. */
function resolve(ref) {
  if (/^[0-9a-f]{40}$/.test(ref)) return ref;
  const out = execFileSync('git', ['ls-remote', `https://github.com/${REPO}.git`, ref], { encoding: 'utf8' });
  const sha = out.split('\n').map((l) => l.split('\t')).find(([, name]) => name === ref || name === `refs/heads/${ref}` || name === `refs/tags/${ref}`)?.[0];
  if (!sha) throw new Error(`${ref} is not a branch, tag or commit in ${REPO}`);
  return sha;
}

async function readSpec(ref) {
  if (process.env.OPENAPI_FILE) return fs.readFileSync(process.env.OPENAPI_FILE, 'utf8');
  const url = `https://raw.githubusercontent.com/${REPO}/${ref}/${SPEC_PATH}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res.text();
}

/** Every property a schema has, following allOf and $ref (a flattened struct). */
function fieldsOf(spec, schema, seen = new Set()) {
  if (!schema || typeof schema !== 'object') return [];
  if (schema.$ref) {
    const name = schema.$ref.replace('#/components/schemas/', '');
    if (seen.has(name)) return [];
    seen.add(name);
    return fieldsOf(spec, spec.components?.schemas?.[name], seen);
  }
  const own = Object.keys(schema.properties ?? {});
  const parts = [...(schema.allOf ?? [])].flatMap((p) => fieldsOf(spec, p, seen));
  return [...new Set([...own, ...parts])].sort();
}

function render(spec, ref) {
  const lines = [
    '// Generated by scripts/openapi-fields.mjs from coderhelm-platform',
    `// ${SPEC_PATH}. Do not edit; run \`npm run openapi:fields\` instead.`,
    '',
    '/** The platform commit this was generated from. */',
    `export const OPENAPI_REF = "${ref}";`,
    '',
    '/** The fields each public API schema has. */',
    'export interface OpenApiFields {',
  ];
  for (const name of Object.keys(spec.components?.schemas ?? {}).sort()) {
    const fields = fieldsOf(spec, spec.components.schemas[name]);
    lines.push(`  ${name}: ${fields.length ? fields.map((f) => JSON.stringify(f)).join(' | ') : 'never'};`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

const ref = resolve(refArg ?? recordedRef() ?? 'main');
const text = render(JSON.parse(await readSpec(ref)), ref);
if (check) {
  const committed = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (committed !== text) {
    console.error(`src/lib/openapi-fields.ts is not what ${REPO}@${ref.slice(0, 12)} documents. Run \`npm run openapi:fields\` and commit the result.`);
    process.exit(1);
  }
  console.log(`openapi-fields.ts matches ${REPO}@${ref.slice(0, 12)}`);
} else {
  fs.writeFileSync(OUT, text);
  console.log(`wrote src/lib/openapi-fields.ts from ${REPO}@${ref.slice(0, 12)}`);
}
